/** Lookup index, built once. */
const FOOD_INDEX: ReadonlyMap<FoodId, Food> = new Map(FOODS.map((f) => [f.id, f]));

/** Throws on an unknown id — a typo in cycle.ts should fail loudly, not render blank. */
export function getFood(id: FoodId): Food {
  const food = FOOD_INDEX.get(id);
  if (!food) throw new Error(`Unknown food id: "${id}"`);
  return food;
}

export function foodExists(id: FoodId): boolean {
  return FOOD_INDEX.has(id);
}
